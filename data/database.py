"""PostgreSQL database for tracking signals, portfolio snapshots, and trades."""

import json
import logging
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from math import isfinite

import psycopg
from psycopg import sql

from constants import DATABASE_URL, SNAPSHOT_GATE_MIN_RATIO, SNAPSHOT_GATE_MAX_AGE_HOURS

logger = logging.getLogger(__name__)

DOUBLE_PRECISION = "DOUBLE PRECISION"
# Cash rather than a position: a trade against it opens or closes only the other coin.
CASH = "USDC"


def get_connection() -> psycopg.Connection:
    return psycopg.connect(DATABASE_URL)


def init_db() -> None:
    with get_connection() as conn:
        _create_schema(conn)
        backfill = not _has_column(conn, "trades", "opened")
        _add_missing_columns(conn)
        _retype_timestamps(conn)
        if backfill:
            _backfill_opened_closed(conn)
    logger.info("Database initialized")


def _create_schema(conn: psycopg.Connection) -> None:
    conn.execute("""
        CREATE TABLE IF NOT EXISTS signals (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            timestamp TIMESTAMPTZ NOT NULL,
            allocations TEXT NOT NULL,
            total_pct DOUBLE PRECISION NOT NULL,
            message_timestamp TEXT
        );

        CREATE TABLE IF NOT EXISTS snapshots (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            timestamp TIMESTAMPTZ NOT NULL,
            signal_id BIGINT REFERENCES signals(id),
            total_value_usd DOUBLE PRECISION NOT NULL,
            balances TEXT NOT NULL,
            prices TEXT NOT NULL,
            values_usd TEXT NOT NULL,
            targets TEXT NOT NULL,
            partial BOOLEAN NOT NULL DEFAULT FALSE,
            fx_currency TEXT,
            fx_rate DOUBLE PRECISION
        );

        CREATE TABLE IF NOT EXISTS trades (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            timestamp TIMESTAMPTZ NOT NULL,
            signal_id BIGINT REFERENCES signals(id),
            symbol TEXT NOT NULL,
            side TEXT NOT NULL,
            amount DOUBLE PRECISION NOT NULL,
            price DOUBLE PRECISION,
            usd_value DOUBLE PRECISION,
            status TEXT NOT NULL,
            order_id TEXT,
            dry_run INTEGER NOT NULL,
            fee_amount DOUBLE PRECISION,
            fee_currency TEXT,
            fee_rate DOUBLE PRECISION,
            direction TEXT,
            perp BOOLEAN,
            fx_currency TEXT,
            fx_rate DOUBLE PRECISION,
            opened TEXT,
            closed TEXT
        );

        CREATE TABLE IF NOT EXISTS settings (
            key TEXT PRIMARY KEY,
            value TEXT NOT NULL
        );
    """)

def _add_missing_columns(conn: psycopg.Connection) -> None:
    """Bring databases created by an earlier version up to the current schema."""
    for table, col, col_type in [
        ("trades", "fee_amount", DOUBLE_PRECISION),
        ("trades", "fee_currency", "TEXT"),
        ("trades", "fee_rate", DOUBLE_PRECISION),
        ("signals", "message_timestamp", "TEXT"),
        ("snapshots", "partial", "BOOLEAN NOT NULL DEFAULT FALSE"),
        # The display currency and its USD rate when the row was written, so a past
        # amount is shown at its own day's rate. NULL when no rate could be had.
        ("snapshots", "fx_currency", "TEXT"),
        ("snapshots", "fx_rate", DOUBLE_PRECISION),
        ("trades", "fx_currency", "TEXT"),
        ("trades", "fx_rate", DOUBLE_PRECISION),
        # 'long' or 'short', and whether the leg was a perp: a short opens with a sell
        # and covers with a buy, which `side` alone cannot tell from a spot trade.
        # NULL on rows written before these were recorded.
        ("trades", "direction", "TEXT"),
        ("trades", "perp", "BOOLEAN"),
        # The coin the trade opened and the one it closed, as its symbol names them
        # (see opened_closed). An `error` row names what it was meant to do.
        ("trades", "opened", "TEXT"),
        ("trades", "closed", "TEXT"),
    ]:
        conn.execute(
            sql.SQL("ALTER TABLE {} ADD COLUMN IF NOT EXISTS {} " + col_type).format(
                sql.Identifier(table), sql.Identifier(col)
            )
        )


def _has_column(conn: psycopg.Connection, table: str, column: str) -> bool:
    return conn.execute(
        """SELECT 1 FROM information_schema.columns
           WHERE table_schema = current_schema() AND table_name = %s AND column_name = %s""",
        (table, column),
    ).fetchone() is not None


def _backfill_opened_closed(conn: psycopg.Connection) -> None:
    """Fill opened/closed on the trades written before they were recorded.

    A spot trade is always long, so its side says it all. A perp row from before
    `direction` was recorded cannot tell a short being opened from a long being
    closed, and is left NULL.
    """
    rows = conn.execute(
        """SELECT id, symbol, side, direction FROM trades
           WHERE direction IS NOT NULL OR position(':' IN symbol) = 0"""
    ).fetchall()
    updates = [(*opened_closed(symbol, side, direction or "long"), row_id)
               for row_id, symbol, side, direction in rows]
    with conn.cursor() as cur:
        cur.executemany("UPDATE trades SET opened = %s, closed = %s WHERE id = %s", updates)
    logger.info("Backfilled opened/closed on %d of the earlier trades", len(updates))


def _retype_timestamps(conn: psycopg.Connection) -> None:
    """Promote timestamp columns to TIMESTAMPTZ.

    The SQLite migration carried them over as ISO text, leaving every range query
    to compare bytes rather than instants. Naive columns are converted too: mixing
    them with the aware datetimes this module writes raises at runtime.
    """
    for table in ("signals", "snapshots", "trades"):
        legacy = conn.execute(
            """SELECT data_type FROM information_schema.columns
               WHERE table_schema = current_schema() AND table_name = %s
                 AND column_name = 'timestamp'
                 AND data_type IN ('text', 'timestamp without time zone')""",
            (table,),
        ).fetchone()
        if not legacy:
            continue
        logger.info("Converting %s.timestamp from %s to timestamptz", table, legacy[0])
        conn.execute(
            sql.SQL(
                "ALTER TABLE {} ALTER COLUMN timestamp TYPE TIMESTAMPTZ "
                "USING timestamp::TIMESTAMPTZ"
            ).format(sql.Identifier(table))
        )


def record_signal(allocations: dict, message_timestamp: str | None = None) -> int:
    """Store a signal's signed allocations (a short is negative)."""
    # Gross, so a short adds to the book's size rather than cancelling a long.
    total_pct = sum(abs(pct) for pct in allocations.values())
    with get_connection() as conn:
        signal_id = conn.execute(
            """INSERT INTO signals (timestamp, allocations, total_pct, message_timestamp)
               VALUES (%s, %s, %s, %s) RETURNING id""",
            (datetime.now(timezone.utc), json.dumps(allocations), total_pct, message_timestamp),
        ).fetchone()[0]
    logger.info("Recorded signal id=%d with %d assets totaling %.1f%% (msg_time=%s)",
                signal_id, len(allocations), total_pct, message_timestamp)
    return signal_id


def _is_collapse(total_value_usd: float, now: datetime, previous: dict | None) -> bool:
    """True when a total is too far below a recent clean snapshot to be a real drawdown.

    Backstop for the degraded-venue check in Balance.degraded, for failures that
    report a plausible-looking total instead of raising. `previous` must be a clean
    snapshot, or a single bad row would become the benchmark that admits the next
    one. The gate disarms once that baseline ages out, so a genuine collapse cannot
    wedge writes forever; a baseline dated in the future is ignored for the same
    reason, since its age never grows.
    """
    if not isfinite(total_value_usd):
        return True
    if previous is None or previous["total_value_usd"] <= 0:
        return False
    age = now - previous["timestamp"]
    if not timedelta(0) <= age <= timedelta(hours=SNAPSHOT_GATE_MAX_AGE_HOURS):
        return False
    return total_value_usd < previous["total_value_usd"] * SNAPSHOT_GATE_MIN_RATIO


def record_snapshot(signal_id: int | None, total_value_usd: float,
                    balances: dict, prices: dict, values_usd: dict, targets: dict,
                    partial: bool = False, display_rate: DisplayRate | None = None) -> None:
    """Persist a portfolio valuation.

    `partial` marks a snapshot taken while a venue was unreadable. Those rows are
    kept for the audit trail but excluded from every baseline query, so an outage
    leaves a gap in /performance rather than a false six-digit percentage.
    """
    now = datetime.now(timezone.utc)
    if not partial and _is_collapse(total_value_usd, now, get_latest_snapshot()):
        logger.error(
            "Recording snapshot of $%.2f USD as partial: implausible drop from the last clean one",
            total_value_usd,
        )
        partial = True
    display_rate = display_rate or DisplayRate()

    with get_connection() as conn:
        conn.execute(
            """INSERT INTO snapshots
               (timestamp, signal_id, total_value_usd, balances, prices, values_usd,
                targets, partial, fx_currency, fx_rate)
               VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)""",
            (
                now,
                signal_id,
                total_value_usd,
                json.dumps(balances),
                json.dumps(prices),
                json.dumps(values_usd),
                json.dumps(targets),
                partial,
                display_rate.currency,
                display_rate.rate,
            ),
        )
    logger.info("Recorded %sportfolio snapshot: $%.2f USD",
                "partial " if partial else "", total_value_usd)


@dataclass(frozen=True)
class Fee:
    """What the venue charged for a fill, as ccxt reports it; any part may be unknown."""
    amount: float | None = None
    currency: str | None = None
    rate: float | None = None


@dataclass(frozen=True)
class DisplayRate:
    """The display currency and its USD rate when a row was written, so a past amount
    is shown at its own day's rate. Both None when no rate could be had."""
    currency: str | None = None
    rate: float | None = None


def opened_closed(symbol: str, side: str, direction: str | None) -> tuple[str | None, str | None]:
    """(coin opened, coin closed) by a trade, None where that side is cash or nothing,
    and both None without a direction: a perp sell could open a short or close a long.

    A long opens the coin it buys and closes the one it sells; a short opens on the
    sell and closes on the buy. A cross pair fills both: buying ETH/BTC opens ETH
    and closes BTC. Coins are named as the symbol names them, so a per-thousand
    perp is KSHIB (ccxt upper-cases the k), in step with the row's amount.
    """
    base, _, quote = symbol.partition("/")
    quote = quote.split(":")[0]  # a perp names its settlement coin after the colon
    if side not in ("buy", "sell") or direction not in ("long", "short") or not base or not quote:
        return None, None
    bought, sold = (base, quote) if side == "buy" else (quote, base)
    opened, closed = (sold, bought) if direction == "short" else (bought, sold)
    return (None if opened == CASH else opened), (None if closed == CASH else closed)


def record_trade(signal_id: int | None, symbol: str, side: str, amount: float,
                 price: float | None, usd_value: float | None, status: str,
                 order_id: str | None, dry_run: bool, fee: Fee | None = None,
                 direction: str | None = None, perp: bool | None = None,
                 display_rate: DisplayRate | None = None) -> None:
    fee = fee or Fee()
    display_rate = display_rate or DisplayRate()
    opened, closed = opened_closed(symbol, side, direction)
    with get_connection() as conn:
        conn.execute(
            """INSERT INTO trades
               (timestamp, signal_id, symbol, side, amount, price, usd_value,
                status, order_id, dry_run, fee_amount, fee_currency, fee_rate,
                direction, perp, fx_currency, fx_rate, opened, closed)
               VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s,
                       %s, %s, %s, %s, %s, %s)""",
            (
                datetime.now(timezone.utc),
                signal_id,
                symbol,
                side,
                amount,
                price,
                usd_value,
                status,
                order_id,
                1 if dry_run else 0,
                fee.amount,
                fee.currency,
                fee.rate,
                direction,
                perp,
                display_rate.currency,
                display_rate.rate,
                opened,
                closed,
            ),
        )


def get_latest_signal_id() -> int | None:
    with get_connection() as conn:
        row = conn.execute("SELECT id FROM signals ORDER BY id DESC LIMIT 1").fetchone()
    return row[0] if row else None


def get_latest_allocations() -> dict | None:
    """The newest signal's allocations, signed: a short is negative.

    Never hand these to the rebalancer as targets: it trades spot only. Use
    utils.helpers.split_shorts() to take the shorts out first.
    """
    with get_connection() as conn:
        row = conn.execute("SELECT allocations FROM signals ORDER BY id DESC LIMIT 1").fetchone()
    return json.loads(row[0]) if row else None


def get_recent_trades(limit: int = 5) -> list[dict]:
    with get_connection() as conn:
        rows = conn.execute(
            """SELECT timestamp, symbol, side, amount, usd_value, status, dry_run,
                      direction, perp, fx_currency, fx_rate
               FROM trades ORDER BY id DESC LIMIT %s""",
            (limit,),
        ).fetchall()
    return [
        {
            "timestamp": r[0], "symbol": r[1], "side": r[2], "amount": r[3],
            "usd_value": r[4], "status": r[5], "dry_run": bool(r[6]),
            "direction": r[7], "perp": r[8], "fx_currency": r[9], "fx_rate": r[10],
        }
        for r in rows
    ]


def _clean_snapshot(clause: str, params: tuple = ()) -> dict | None:
    """Read one snapshot taken while every venue was readable.

    Partial rows are deliberately unreachable here: they exist for the audit trail,
    and using one as a baseline is exactly the bug this module guards against.
    """
    with get_connection() as conn:
        row = conn.execute(
            "SELECT timestamp, total_value_usd FROM snapshots "
            f"WHERE NOT partial {clause}",
            params,
        ).fetchone()
    return {"timestamp": row[0], "total_value_usd": row[1]} if row else None


def get_latest_snapshot() -> dict | None:
    return _clean_snapshot("ORDER BY timestamp DESC LIMIT 1")


def get_snapshot_at_or_before(target_ts: datetime) -> dict | None:
    return _clean_snapshot("AND timestamp <= %s ORDER BY timestamp DESC LIMIT 1", (target_ts,))


def get_earliest_snapshot() -> dict | None:
    return _clean_snapshot("ORDER BY timestamp ASC LIMIT 1")


def get_setting(key: str) -> str | None:
    with get_connection() as conn:
        row = conn.execute("SELECT value FROM settings WHERE key = %s", (key,)).fetchone()
    return row[0] if row else None


def set_setting(key: str, value: str) -> None:
    with get_connection() as conn:
        conn.execute(
            """INSERT INTO settings (key, value) VALUES (%s, %s)
               ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value""",
            (key, value),
        )


def get_latest_message_timestamp() -> str | None:
    """Return the newest signal's posted-at timestamp, ignoring unknown ones.

    A scrape that falls back to the page body cannot read a message timestamp
    and records the signal with NULL. Skipping those rows keeps one such scrape
    from resetting the baseline and making the next poll look like a new signal.
    """
    with get_connection() as conn:
        row = conn.execute(
            "SELECT message_timestamp FROM signals "
            "WHERE message_timestamp IS NOT NULL ORDER BY id DESC LIMIT 1"
        ).fetchone()
    return row[0] if row else None
